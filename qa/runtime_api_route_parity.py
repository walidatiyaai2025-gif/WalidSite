#!/usr/bin/env python3
"""T024: compare the REAL booted Laravel route collection to canonical OpenAPI.

The input must be generated by php artisan route:list --json at the same
tested commit. This proves runtime route REGISTRATION, not successful HTTP,
authorization, DTO/schema conformance, deployment, or product readiness.
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path

from qa.api_contract_route_parity import operation_key
from qa.t024_readiness import openapi_operations

ROOT = Path(__file__).resolve().parents[1]
MAX_ROUTE_JSON_BYTES = 4 * 1024 * 1024
METHODS = {"GET", "HEAD", "POST", "PUT", "PATCH", "DELETE", "OPTIONS"}


def check_routes(artisan_output: object, openapi_text: str) -> tuple[dict, list[str]]:
    """Admit only actual host-neutral API/v1 methods from Artisan JSON."""
    report = {
        "scope": "booted Laravel route registration only; NO HTTP or DTO certification",
        "artisan_runtime_registration_verified": False,
        "http_requests_verified": False,
        "authorization_verified": False,
        "dto_payloads_verified": False,
        "production_ready": False,
        "contract_operations": 0,
        "matched_operations": 0,
        "registered_api_route_shapes": 0,
        "missing_operations": [],
        "duplicate_registrations": [],
        "domain_restricted_contract_routes": [],
        "uncontracted_registrations": [],
    }
    try:
        _, declared = openapi_operations(openapi_text)
        expected = {}
        for item in declared:
            path, verb = item.rsplit("#", 1)
            key = operation_key(path, verb)
            if key in expected:
                raise ValueError("Contract repeats a normalized method/path")
            expected[key] = verb.upper() + " " + path
        if not isinstance(artisan_output, list) or not 1 <= len(artisan_output) <= 5000:
            raise ValueError("Artisan route list is absent or unbounded")
        registered: dict[str, list[str]] = defaultdict(list)
        restricted: set[str] = set()
        for route in artisan_output:
            if not isinstance(route, dict):
                raise ValueError("Invalid Laravel route record")
            uri, method = route.get("uri"), route.get("method")
            if not isinstance(uri, str) or not isinstance(method, str):
                raise ValueError("Missing Laravel route method/URI")
            if not uri.startswith("api/v1/"):
                continue
            path = uri[len("api/v1"):]
            verbs = method.split("|")
            if not verbs or len(set(verbs)) != len(verbs) or not set(verbs) <= METHODS:
                raise ValueError("Unexpected Laravel route verbs")
            # Laravel automatically registers HEAD along with GET; this
            # implicit alias is not a second contracted GET operation.
            if "GET" in verbs:
                verbs.remove("HEAD") if "HEAD" in verbs else None
            for verb in verbs:
                key = operation_key(path, verb.lower())
                label = verb + " " + path
                domain = route.get("domain")
                if domain not in (None, ""):
                    if key in expected:
                        restricted.add(expected[key])
                    continue
                registered[key].append(label)

        missing = sorted(expected[key] for key in expected.keys() - registered.keys())
        duplicate = sorted(value for values in registered.values()
                           if len(values) > 1 for value in values)
        extra = sorted(value for key, values in registered.items()
                       if key not in expected for value in values)
        report.update({
            "contract_operations": len(declared),
            "matched_operations": len(declared) - len(missing),
            "registered_api_route_shapes": len(registered),
            "missing_operations": missing,
            "duplicate_registrations": duplicate,
            "domain_restricted_contract_routes": sorted(restricted),
            "uncontracted_registrations": extra,
        })
        errors = []
        if missing:
            errors.append("Booted Laravel is missing contracted OpenAPI routes")
        if duplicate:
            errors.append("Booted Laravel contains duplicate/shadowed API routes")
        if restricted:
            errors.append("Contracted API routes have a domain-specific registration")
        report["artisan_runtime_registration_verified"] = not errors
        return report, errors
    except (TypeError, ValueError, KeyError, AttributeError):
        return report, ["Invalid Artisan JSON or OpenAPI source"]


def audit(root: Path, artisan_json: Path) -> tuple[dict, list[str]]:
    report = {
        "artisan_runtime_registration_verified": False,
        "http_requests_verified": False,
        "production_ready": False,
    }
    try:
        if artisan_json.is_symlink() or not artisan_json.is_file():
            raise ValueError("Missing or linked Artisan output")
        if not 0 < artisan_json.stat().st_size <= MAX_ROUTE_JSON_BYTES:
            raise ValueError("Oversized Artisan route output")
        raw = artisan_json.read_bytes()
        if not 0 < len(raw) <= MAX_ROUTE_JSON_BYTES:
            raise ValueError("Invalid Artisan route size")
        parsed = json.loads(raw.decode("utf-8"))
        source = (root / "api/openapi-contract.yaml").read_text(encoding="utf-8")
        return check_routes(parsed, source)
    except (OSError, UnicodeError, ValueError, TypeError):
        return report, ["Cannot verify booted Laravel route data"]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--artisan-json", type=Path, required=True)
    args = parser.parse_args(argv)
    report, errors = audit(args.root, args.artisan_json)
    report["audit_errors"] = errors
    print(json.dumps(report, ensure_ascii=False, indent=2, sort_keys=True))
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
